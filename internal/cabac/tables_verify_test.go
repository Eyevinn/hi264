package cabac

import (
	"fmt"
	"testing"
)

// TestRangeTabLPS_AgainstStandard compares the Go rangeTabLPS table
// against Table 9-44 from the H.264 standard (ISO/IEC 14496-10).
func TestRangeTabLPS_AgainstStandard(t *testing.T) {
	// Table 9-44 from the H.264 standard, indexed by [pStateIdx][qCodIRangeIdx]
	standard := [64][4]uint16{
		{128, 176, 208, 240}, // 0
		{128, 167, 197, 227}, // 1
		{128, 158, 187, 216}, // 2
		{123, 150, 178, 205}, // 3
		{116, 142, 169, 195}, // 4
		{111, 135, 160, 185}, // 5
		{105, 128, 152, 175}, // 6
		{100, 122, 144, 166}, // 7
		{95, 116, 137, 158},  // 8
		{90, 110, 130, 150},  // 9
		{85, 104, 123, 142},  // 10
		{81, 99, 117, 135},   // 11
		{77, 94, 111, 128},   // 12
		{73, 89, 105, 122},   // 13
		{69, 85, 100, 116},   // 14
		{66, 80, 95, 110},    // 15
		{62, 76, 90, 104},    // 16
		{59, 72, 86, 99},     // 17
		{56, 69, 81, 94},     // 18
		{53, 65, 77, 89},     // 19
		{51, 62, 73, 85},     // 20
		{48, 59, 69, 80},     // 21
		{46, 56, 66, 76},     // 22
		{43, 53, 63, 72},     // 23
		{41, 50, 59, 69},     // 24
		{39, 48, 56, 65},     // 25
		{37, 45, 54, 62},     // 26
		{35, 43, 51, 59},     // 27
		{33, 41, 48, 56},     // 28
		{32, 39, 46, 53},     // 29
		{30, 37, 43, 50},     // 30
		{29, 35, 41, 48},     // 31
		{27, 33, 39, 45},     // 32
		{26, 31, 37, 43},     // 33
		{24, 30, 35, 41},     // 34
		{23, 28, 33, 39},     // 35
		{22, 27, 32, 37},     // 36
		{21, 26, 30, 35},     // 37
		{20, 24, 29, 33},     // 38
		{19, 23, 27, 31},     // 39
		{18, 22, 26, 30},     // 40
		{17, 21, 25, 28},     // 41
		{16, 20, 23, 27},     // 42
		{15, 19, 22, 25},     // 43
		{14, 18, 21, 24},     // 44
		{14, 17, 20, 23},     // 45
		{13, 16, 19, 22},     // 46
		{12, 15, 18, 21},     // 47
		{12, 14, 17, 20},     // 48
		{11, 14, 16, 19},     // 49
		{11, 13, 15, 18},     // 50
		{10, 12, 15, 17},     // 51
		{10, 12, 14, 16},     // 52
		{9, 11, 13, 15},      // 53
		{9, 11, 12, 14},      // 54
		{8, 10, 12, 14},      // 55
		{8, 9, 11, 13},       // 56
		{7, 9, 11, 12},       // 57
		{7, 9, 10, 12},       // 58
		{7, 8, 10, 11},       // 59
		{6, 8, 9, 11},        // 60
		{6, 7, 9, 10},        // 61
		{6, 7, 8, 9},         // 62
		{2, 2, 2, 2},         // 63
	}

	mismatches := 0
	for pStateIdx := 0; pStateIdx < 64; pStateIdx++ {
		for qIdx := 0; qIdx < 4; qIdx++ {
			got := rangeTabLPS[pStateIdx][qIdx]
			want := standard[pStateIdx][qIdx]
			if got != want {
				t.Errorf("rangeTabLPS[%d][%d] = %d, want %d (from standard Table 9-44)",
					pStateIdx, qIdx, got, want)
				mismatches++
			}
		}
	}

	if mismatches == 0 {
		fmt.Println("All 256 rangeTabLPS entries match the H.264 standard Table 9-44.")
	} else {
		t.Errorf("Total mismatches: %d out of 256 entries", mismatches)
	}
}
